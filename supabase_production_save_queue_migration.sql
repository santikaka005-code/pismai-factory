create or replace function public.claim_next_production_save_queue(p_worker_id text)
returns setof public.production_save_queue
language plpgsql
security definer
set search_path = public
as $$
declare
  claimed_id bigint;
begin
  -- A Render restart must not leave a job permanently locked. Five minutes
  -- also prevents a slow in-flight request from being claimed by two workers.
  update public.production_save_queue
  set status = 'queued',
      locked_at = null,
      locked_by = null,
      next_attempt_at = now(),
      error_code = 'stale_worker_recovered',
      error_message = 'Recovered after the previous worker stopped responding.'
  where status = 'processing'
    and locked_at < now() - interval '5 minutes';

  select id into claimed_id
  from public.production_save_queue
  where status = 'queued'
    and next_attempt_at <= now()
    and attempt_count < max_attempts
  order by id asc
  for update skip locked
  limit 1;

  if claimed_id is null then
    return;
  end if;

  return query
  update public.production_save_queue
  set status = 'processing',
      attempt_count = attempt_count + 1,
      locked_at = now(),
      locked_by = nullif(trim(p_worker_id), ''),
      started_at = coalesce(started_at, now()),
      error_code = null,
      error_message = null
  where id = claimed_id
  returning *;
end;
$$;

