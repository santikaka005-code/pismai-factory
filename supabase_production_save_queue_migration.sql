-- Pismai production save queue.
-- Additive only: this migration does not modify or delete existing production records.

alter table public.production_records
  add column if not exists queue_dedupe_key text;

create unique index if not exists production_records_queue_dedupe_key_unique
  on public.production_records(queue_dedupe_key)
  where queue_dedupe_key is not null;

create table if not exists public.production_save_queue (
  id bigint generated by default as identity primary key,
  queue_uid text not null,
  batch_uid text,
  payload jsonb not null,
  payload_hash text not null,
  record_count integer not null,
  fruit_type text not null,
  record_date date not null,
  employee_id bigint,
  emp_code text not null,
  employee_name text not null default '',
  total_weight numeric(14,3) not null default 0,
  total_amount numeric(14,2) not null default 0,
  status text not null default 'queued',
  attempt_count integer not null default 0,
  max_attempts integer not null default 3,
  next_attempt_at timestamptz not null default now(),
  locked_at timestamptz,
  locked_by text,
  started_at timestamptz,
  finished_at timestamptz,
  result_record_ids bigint[] not null default '{}',
  result_payload jsonb not null default '[]'::jsonb,
  duplicate_details jsonb not null default '{}'::jsonb,
  error_code text,
  error_message text,
  created_by text not null,
  cancelled_by text,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint production_save_queue_uid_unique unique (queue_uid),
  constraint production_save_queue_payload_array check (jsonb_typeof(payload) = 'array'),
  constraint production_save_queue_record_count check (record_count between 1 and 100),
  constraint production_save_queue_status_check check (
    status in ('queued', 'processing', 'succeeded', 'needs_review', 'failed', 'cancelled')
  ),
  constraint production_save_queue_attempt_check check (
    attempt_count >= 0 and max_attempts between 1 and 10
  )
);

create index if not exists idx_production_save_queue_work
  on public.production_save_queue(status, next_attempt_at, id);
create index if not exists idx_production_save_queue_created
  on public.production_save_queue(created_at desc);
create index if not exists idx_production_save_queue_employee
  on public.production_save_queue(record_date, emp_code, fruit_type);
create index if not exists idx_production_save_queue_creator
